add_rules("mode.debug", "mode.release")
set_languages("c++20")
set_allowedplats("windows")
set_allowedarchs("x64")
set_targetdir("build/$(plat)/$(arch)/$(mode)")
set_runtimes("MT")
add_requires("minhook 1.3.4", {configs = {shared = false}})
add_includedirs("include", "vendor/json")
add_defines("WIN32_LEAN_AND_MEAN=", "NOMINMAX=")
add_cxflags("/utf-8", "/W4", "/EHsc")
target("ToggleSprintConfigTests")
    set_kind("binary")
    add_files("tests/ConfigTests.cpp", "src/Config.cpp", "src/KeyToken.cpp")
target_end()

option("modmenu_source")
    set_showmenu(true)
    set_description("Optional ModMenuBedrock checkout for settings integration tests")
option_end()

if get_config("modmenu_source") then
    local menu = path.absolute(get_config("modmenu_source"))
    target("ToggleSprintModMenuTests")
        set_kind("binary")
        add_files("tests/ModMenuTests.cpp", "src/Config.cpp", "src/KeyToken.cpp")
        for _, file in ipairs({"Settings", "SettingsInput", "SettingsSchema", "SettingsDescription", "Storage", "Slider", "TextEditor"}) do
            add_files(path.join(menu, "src", file .. ".cpp"))
        end
        add_includedirs(path.join(menu, "include"))
    target_end()
end

